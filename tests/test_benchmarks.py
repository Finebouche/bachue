import numpy as np
import pytest

from bachue.datasets.benchmarks import KINDS, load, names, spectral_representation_of


def test_names_and_kinds():
    assert "MackeyGlass" in names("forecasting") and "JapaneseVowels" in names("classification")
    assert names("categorical_forecasting") == ["Canary"]
    assert names() == sorted(KINDS) and set(KINDS.values()) == {"forecasting", "classification",
                                                                 "categorical_forecasting"}
    assert spectral_representation_of("JapaneseVowels") == "mfcc" and spectral_representation_of("Lorenz") == "stft"
    with pytest.raises(ValueError):
        load("NoSuchDataset")


@pytest.mark.parametrize("name", ["MackeyGlass", "Lorenz"])
def test_forecasting_dataset(name):
    # (generated by hag, without download) inputs scaled in [0, 1] on the train set, a target for each step
    data = load(name)
    assert data.kind == "forecasting" and not data.is_instances_classification
    assert data.train.ndim == 2 and len(data.train) == len(data.Y_train) and len(data.test) == len(data.Y_test)
    assert data.train.shape[1] == data.test.shape[1]
    assert data.train.min() >= -1e-9 and data.train.max() <= 1 + 1e-9
    assert np.all(np.isfinite(data.train)) and np.all(np.isfinite(np.asarray(data.Y_train, dtype=float)))
